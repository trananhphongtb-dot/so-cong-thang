    fun errNumberExists(n: Int): String =
        if (weekdays.first() == "Mon") "Number $n already exists, pick another one."
        else "Số $n đã có rồi, chọn số khác."
    fun monthTitle(year: Int, month: Int): String =
        if (weekdays.first() == "Mon") {
            val names = listOf(
                "January", "February", "March", "April", "May", "June",
                "July", "August", "September", "October", "November", "December"
            )
            "${names[month]} $year"
        } else {
            "Tháng ${month + 1} / $year"
        }
    fun dayTitle(day: Int, month: Int, year: Int): String =
        if (weekdays.first() == "Mon") "$day/${month + 1}/$year" else "Ngày $day/${month + 1}/$year"
    fun jobLabel(jobNumber: Int, jobName: String): String =
        if (weekdays.first() == "Mon") "No. $jobNumber - $jobName" else "Số $jobNumber - $jobName"
    fun unfinishedDayLabel(day: Int, month: Int): String =
        if (weekdays.first() == "Mon") "Day $day/$month" else "Ngày $day/$month"
    fun scheduledMarker(): String = if (weekdays.first() == "Mon") " •Set" else " •Hẹn"
}

